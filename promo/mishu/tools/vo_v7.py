"""Voice-over for 米麦 产品说明书 v7 — offline Chinese TTS (sherpa-onnx + Kokoro multi-lang v1.0, Apache-2.0).

usage: python3 -I vo_v7.py <kokoro_model_dir> <out_dir> [sid] [speed]
  writes <out_dir>/vo_XX.wav (24 kHz mono, one per line) and ../v7_vo.js (line start, phrase timings for the captions).
Each phrase is synthesised on its own and joined with fixed pauses: Kokoro otherwise breathes an "啊" into commas,
and per-phrase timing lets the on-screen caption build word group by word group in sync with the voice.
The model is not in the repo: https://github.com/k2-fsa/sherpa-onnx/releases/download/tts-models/kokoro-multi-lang-v1_0.tar.bz2
"""
import json
import os
import sys

import numpy as np
import sherpa_onnx
import soundfile as sf

# (start time s, phrases). A phrase ending in '，' gets a short pause, '。' a longer one.
LINES = [
    (3.75, ['这是一份', '关于你的说明书。']),
    (6.45, ['你的脸，', '你的声音，', '你的灵感，']),
    (13.15, ['都是你的资产。']),
    (15.35, ['第一步，上传。']),
    (17.25, ['在你的设备上加密，', '只有你能打开。']),
    (21.35, ['第二步，上架。']),
    (23.0, ['卖的是使用权。', '所有权，', '永远是你的。']),
    (27.4, ['第三步，授权。']),
    (29.25, ['每一次使用，', '都要你亲自点头。']),
    (34.35, ['第四步，掌控。']),
    (36.25, ['钥匙，只在你手里，', '随时可以收回。']),
    (40.35, ['第五步，收益。']),
    (42.3, ['每用一次，', '就到账一次。']),
    (51.85, ['一切，', '由你决定。']),
    (54.0, ['密码保护资产，', '数学生长价值。']),
    (57.2, ['密数科学研究院，', '出品。']),
]
GAP = {'，': 0.16, '。': 0.3, '': 0.04}


def tts(model_dir):
    D = model_dir
    cfg = sherpa_onnx.OfflineTtsConfig(model=sherpa_onnx.OfflineTtsModelConfig(
        kokoro=sherpa_onnx.OfflineTtsKokoroModelConfig(
            model=D + '/model.onnx', voices=D + '/voices.bin', tokens=D + '/tokens.txt',
            data_dir=D + '/espeak-ng-data', dict_dir=D + '/dict',
            lexicon=D + '/lexicon-us-en.txt,' + D + '/lexicon-zh.txt'),
        num_threads=4), rule_fsts=D + '/date-zh.fst,' + D + '/number-zh.fst')
    return sherpa_onnx.OfflineTts(cfg)


def trim(x, sr, thr=0.012):
    """drop leading/trailing silence, keep a little air."""
    idx = np.where(np.abs(x) > thr)[0]
    if len(idx) == 0:
        return x
    a = max(0, idx[0] - int(0.02 * sr)); b = min(len(x), idx[-1] + int(0.05 * sr))
    return x[a:b]


def phrase(T, text, sid, speed):
    body = text.rstrip('，。')
    a = T.generate(body + '。', sid=sid, speed=speed)   # a full stop keeps the cadence falling, with no tail breath
    x = trim(np.asarray(a.samples, dtype=np.float32), a.sample_rate)
    n = int(0.012 * a.sample_rate)                       # tiny fades: no clicks at the joins
    x[:n] *= np.linspace(0, 1, n); x[-n:] *= np.linspace(1, 0, n)
    return x, a.sample_rate


def main():
    model_dir, out = sys.argv[1], sys.argv[2]
    sid = int(sys.argv[3]) if len(sys.argv) > 3 else 48
    speed = float(sys.argv[4]) if len(sys.argv) > 4 else 0.95
    os.makedirs(out, exist_ok=True)
    T = tts(model_dir)
    rows = []
    for i, (t0, phrases) in enumerate(LINES):
        parts, ph, cur, sr = [], [], 0.0, 24000
        for k, p in enumerate(phrases):
            x, sr = phrase(T, p, sid, speed)
            ph.append({'s': p, 'a': round(cur, 3), 'b': round(cur + len(x) / sr, 3)})
            parts.append(x); cur += len(x) / sr
            if k < len(phrases) - 1:
                g = GAP[p[-1] if p[-1] in GAP else '']
                parts.append(np.zeros(int(g * sr), np.float32)); cur += g
        y = np.concatenate(parts)
        sf.write(os.path.join(out, f'vo_{i:02d}.wav'), y, sr)
        rows.append({'t': t0, 'd': round(len(y) / sr, 3), 'ph': ph})
        print(f'{i:02d} {t0:6.2f} +{len(y) / sr:4.2f} → {t0 + len(y) / sr:6.2f}  {"".join(phrases)}')
    for p, q in zip(rows, rows[1:]):
        if p['t'] + p['d'] > q['t'] - 0.1:
            print('OVERLAP at', q['t'])
    js = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'v7_vo.js')
    with open(js, 'w', encoding='utf-8') as f:
        f.write('// generated by tools/vo_v7.py — voice-over timings (s): line start t, length d, phrases [a, b] from t\n')
        f.write('window.V7_VO = ' + json.dumps(rows, ensure_ascii=False) + ';\n')


if __name__ == '__main__':
    main()
