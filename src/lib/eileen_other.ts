type WashKey = 'dress' | 'pants' | 'hair' | 'skin' | 'blush' | 'shade' | 'scarf' | 'jade' | 'paper' | 'wood' | 'gold' | 'leather' | 'sea'
type LineCol = 'rouge' | 'jade' | 'soft'
type Item =
  | { k: 'l'; d: string; w: number; a: number; fine: boolean; g?: string; col?: LineCol }
  | { k: 'h'; d: string; ang: number; gap: number; w: number; a: number; g?: string; cross?: boolean }
  | { k: 'w'; d: string; c: WashKey; a: number; g?: string }
  | { k: 'd'; x: number; y: number; r: number; g?: string; a: number }
type Group = { px: number; py: number; rot: number; dx?: number; dy?: number; sc?: number }
type PoseDef = { items: Item[]; groups?: Record<string, Group> }

// builders (g = current group, set with grp())
let G: string | undefined
const grp = (g?: string) => { G = g }
/** contour line */
const L = (d: string, w = 1, a = 1, col?: LineCol): Item => ({ k: 'l', d, w, a, fine: false, g: G, col })
/** fine line (face, fingers): low wobble */
const F = (d: string, w = 0.7, a = 1, col?: LineCol): Item => ({ k: 'l', d, w, a, fine: true, g: G, col })
const Hh = (d: string, ang: number, gap: number, w = 0.55, a = 0.55, cross = false): Item => ({ k: 'h', d, ang, gap, w, a, g: G, cross })
const Wa = (d: string, c: WashKey, a = 0.5): Item => ({ k: 'w', d, c, a, g: G })
const D = (x: number, y: number, r: number, a = 1): Item => ({ k: 'd', x, y, r, g: G, a })

/** ellipse as cubic path */
function ell(cx: number, cy: number, rx: number, ry: number) {
  const k = 0.5523
  return `M${cx + rx} ${cy} C${cx + rx} ${cy + k * ry} ${cx + k * rx} ${cy + ry} ${cx} ${cy + ry} C${cx - k * rx} ${cy + ry} ${cx - rx} ${cy + k * ry} ${cx - rx} ${cy} C${cx - rx} ${cy - k * ry} ${cx - k * rx} ${cy - ry} ${cx} ${cy - ry} C${cx + k * rx} ${cy - ry} ${cx + rx} ${cy - k * ry} ${cx + rx} ${cy}`
}
/** open arc of an ellipse from angle a0 to a1 (radians, y down) */
function arc(cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, n = 10) {
  let s = ''
  for (let i = 0; i <= n; i++) {
    const a = a0 + ((a1 - a0) * i) / n
    s += `${i ? 'L' : 'M'}${(cx + Math.cos(a) * rx).toFixed(1)} ${(cy + Math.sin(a) * ry).toFixed(1)} `
  }
  return s
}

