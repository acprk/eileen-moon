type CItem = { it: Item; polys: Poly[]; len: number }
const POSES: Partial<Record<EileenPose, () => PoseDef>> = { child: poseChild, girlWindow: poseGirl, shipRail: poseShip, oldProfile: poseProfile, oldAtDesk: poseDesk }
const compiled = new Map<string, CItem[]>()

function applyGroup(polys: Poly[], g?: Group): Poly[] {
  if (!g) return polys
  const sc = g.sc ?? 1
  const c = Math.cos(g.rot), s = Math.sin(g.rot)
  return polys.map((p) => {
    const out: Poly = new Array(p.length)
    for (let i = 0; i < p.length; i += 2) {
      const dx = (p[i] - g.px) * sc, dy = (p[i + 1] - g.py) * sc
      out[i] = g.px + dx * c - dy * s + (g.dx ?? 0)
      out[i + 1] = g.py + dx * s + dy * c + (g.dy ?? 0)
    }
    return out
  })
}

function compile(pose: EileenPose): CItem[] | null {
  const hit = compiled.get(pose)
  if (hit) return hit
  const mk = POSES[pose]
  if (!mk) return null
  G = undefined
  const def = mk()
  const out: CItem[] = []
  for (const it of def.items) {
    const g = it.g ? def.groups?.[it.g] : undefined
    const polys = it.k === 'd' ? applyGroup([[it.x, it.y, it.x + 0.01, it.y]], g) : applyGroup(pathPolys(it.d, 2.5), g)
    let len = 0
    if (it.k === 'l') len = polys.reduce((a, p) => a + polyLength(p), 0)
    else if (it.k === 'd') len = it.r * 3
    else if (it.k === 'h') {
      let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9
      for (const p of polys) for (let i = 0; i < p.length; i += 2) {
        x0 = Math.min(x0, p[i]); x1 = Math.max(x1, p[i]); y0 = Math.min(y0, p[i + 1]); y1 = Math.max(y1, p[i + 1])
      }
      len = Math.hypot(x1 - x0, y1 - y0) * 1.2
    }
    out.push({ it, polys, len })
  }
  compiled.set(pose, out)
  return out
}

function hex(c: string): [number, number, number] {
  let m = c.replace('#', '')
  if (m.length === 3) m = m[0] + m[0] + m[1] + m[1] + m[2] + m[2]
  return [parseInt(m.slice(0, 2), 16), parseInt(m.slice(2, 4), 16), parseInt(m.slice(4, 6), 16)]
}
function mix(a: string, b: string, k: number) {
  const A = hex(a), B = hex(b)
  return `rgb(${Math.round(A[0] + (B[0] - A[0]) * k)},${Math.round(A[1] + (B[1] - A[1]) * k)},${Math.round(A[2] + (B[2] - A[2]) * k)})`
}
function lum(c: string) {
  if (!/^#([0-9a-f]{3}|[0-9a-f]{6})$/i.test(c)) return 0
  const [r, g, b] = hex(c)
  return (0.299 * r + 0.587 * g + 0.114 * b) / 255
}

