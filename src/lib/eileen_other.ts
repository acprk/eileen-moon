/** fine pigment granulation (much finer than pen.ts wash speckle, which reads as freckles on faces) */
function grain() {
  return cached('eo:grain', 160, 160, (g) => {
    for (let i = 0; i < 1600; i++) {
      g.fillStyle = `rgba(50,35,25,${0.15 + rand(i, 31) * 0.45})`
      g.beginPath()
      g.arc(rand(i, 32) * 160, rand(i, 33) * 160, 0.3 + rand(i, 34) * 0.7, 0, Math.PI * 2)
      g.fill()
    }
  })
}

/** watercolour wash: soft body, pooled edge, optional fine granulation */
function paint(ctx: Ctx, polys: Poly[], color: string, alpha: number, blur: number, gran: number) {
  if (alpha <= 0.002) return
  const path = new Path2D()
  for (const p of polys) {
    path.moveTo(p[0], p[1])
    for (let i = 2; i < p.length; i += 2) path.lineTo(p[i], p[i + 1])
    path.closePath()
  }
  ctx.save()
  const a0 = ctx.globalAlpha * alpha
  ctx.globalAlpha = a0
  ctx.filter = `blur(${blur.toFixed(2)}px)`
  ctx.fillStyle = color
  ctx.fill(path)
  ctx.filter = `blur(${(blur * 0.5).toFixed(2)}px)`
  ctx.strokeStyle = color
  ctx.lineWidth = Math.max(1, blur * 0.9)
  ctx.globalAlpha = a0 * 0.45
  ctx.stroke(path)
  ctx.filter = 'none'
  if (gran > 0) {
    ctx.clip(path)
    ctx.globalAlpha = a0 * gran
    ctx.globalCompositeOperation = 'multiply'
    ctx.fillStyle = ctx.createPattern(grain(), 'repeat')!
    ctx.fill(path)
  }
  ctx.restore()
}

export function drawOther(ctx: Ctx, pose: EileenPose, o: EileenOpts) {
  const items = compile(pose)
  if (!items) return
  const s = o.h / 1000
  const flip = !!o.flip
  const X = (v: number) => o.x + (flip ? 500 - v : v - 500) * s
  const Y = (v: number) => o.y + (v - 1000) * s
  const tr = (polys: Poly[]) => polys.map((p) => p.map((v, i) => (i & 1 ? Y(v) : X(v))))
  const col = o.color ?? C.ink
  const night = lum(col) > 0.55
  const maskMode = /^#f{3}(f{3})?$/i.test(col)
  const progress = clamp(o.progress ?? 1)
  const fill = clamp(o.fill ?? 1)
  const t = o.t ?? 0
  const boil = o.boil ?? 8
  const k = Math.pow(o.h / 600, 0.72)
  const wt = (o.weight ?? 1) * k
  const lineCol = (lc?: LineCol) => (!lc || night ? col : lc === 'rouge' ? C.rouge : lc === 'jade' ? C.jade : C.inkSoft)

  // 1) washes, fading in with fill (lightly tied to progress so colour never precedes the line)
  const wf = fill * clamp(progress * 1.4 - 0.2)
  if (wf > 0) {
    for (const ci of items) {
      if (ci.it.k !== 'w') continue
      const ck = ci.it.c
      if (maskMode) {
        const mc = ck === 'dress' ? o.dress ?? '#666' : MASK[ck]
        if (mc) paint(ctx, tr(ci.polys), mc, 0.92 * wf, 1.2 * k, 0)
        continue
      }
      const [c, am] = washColor(ck, o, pose, night, col)
      const gran = ck === 'skin' || ck === 'blush' || ck === 'gold' || ck === 'sea' || night ? 0 : ck === 'hair' ? 0.15 : 0.3
      paint(ctx, tr(ci.polys), c, ci.it.a * am * wf, (ck === 'blush' ? 6 : 2) * k, gran)
    }
  }
  // 2) lines, dots and hatching, revealed in order
  const ov = 0.12
  let total = 0
  for (const ci of items) total += ci.len
  const span = progress * total * (1 + ov)
  let acc = 0
  let idx = 0
  for (const ci of items) {
    const it = ci.it
    if (it.k === 'w') continue
    idx++
    const start = acc * (1 - ov * 0.5)
    acc += ci.len
    const lp = clamp((span - start) / Math.max(1e-6, ci.len))
    if (lp <= 0) continue
    if (it.k === 'l') {
      const polys = tr(ci.polys)
      const lens = polys.map(polyLength)
      const tot = lens.reduce((a, b) => a + b, 0)
      let a2 = 0
      for (let j = 0; j < polys.length; j++) {
        const pl = clamp((lp * tot - a2) / Math.max(1e-6, lens[j]))
        a2 += lens[j]
        if (pl <= 0) break
        const L0 = lens[j]
        penStroke(ctx, polys[j], pl, {
          width: 2.1 * wt * it.w,
          color: lineCol(it.col),
          alpha: it.a,
          wobble: (it.fine ? 0.22 : 0.7) * k,
          wave: (it.fine ? 60 : 110) * k,
          pressure: it.fine ? 0.2 : 0.35,
          taperIn: Math.min(12 * k, L0 * 0.3),
          taperOut: Math.min(20 * k, L0 * 0.42),
          boil, t, seed: idx * 7 + j,
          nib: !it.fine,
        })
      }
    } else if (it.k === 'd') {
      const cx = X(ci.polys[0][0]), cy = Y(ci.polys[0][1])
      ctx.save()
      ctx.globalAlpha *= it.a * clamp(lp * 1.5)
      ctx.fillStyle = col
      ctx.beginPath()
      ctx.arc(cx, cy, it.r * s * (0.6 + 0.4 * lp), 0, Math.PI * 2)
      ctx.fill()
      ctx.restore()
    } else if (it.k === 'h') {
      const ang = flip ? Math.PI - it.ang : it.ang
      hatch(ctx, tr(ci.polys), {
        angle: ang, gap: Math.max(2.2, it.gap * s), progress: lp, cross: it.cross,
        width: 1.6 * wt * it.w, color: col, alpha: it.a, wobble: 0.35 * k, wave: 50 * k,
        taperIn: 5 * k, taperOut: 7 * k, boil, t, seed: idx * 3,
      })
    }
  }
}
